mod common;
use common::{fixture_repo, read, write};
use tempa_core::config::Config;
use tempa_core::import::import;
use tempa_core::sync::{drift, sync};

#[test]
fn imports_claude_heavy() {
    let d = fixture_repo("claude-heavy");
    let r = import(d.path(), true).unwrap();
    let agents = read(d.path(), "AGENTS.md");
    assert!(agents.starts_with("# Billing API\n"), "{agents}");
    assert!(agents.contains("## Konvensi\n\nGunakan snake_case."), "{agents}");
    assert!(!agents.contains("@docs/style.md"));
    assert!(agents.contains("## Imported from .cursorrules\n\nJangan sentuh folder legacy/."), "{agents}");
    assert_eq!(r.duplicates_skipped, 1);
    assert_eq!(r.harness_added, vec![("format".to_string(), "cargo fmt --check".to_string())]);
    assert_eq!(r.protected_added, vec!["secrets/**".to_string()]); // ".env*" already in defaults
    assert!(r.gaps.iter().any(|g| g.contains("Bash(rm -rf:*)")), "{:?}", r.gaps);
    assert!(r.gaps.iter().any(|g| g.contains("prettier")), "{:?}", r.gaps);
    assert!(r.merged_from.contains(&"CLAUDE.md".to_string()));
    assert!(r.written.contains(&"tempa.toml".to_string()));
    for p in [
        ".tempa/commands/db/migrate.md",
        ".tempa/commands/review kode.md",
        ".tempa/agents/tester.md",
        ".tempa/skills/adr/SKILL.md",
        ".tempa/skills/adr/template.md",
        ".tempa/targets/.claude/settings.json",
    ] {
        assert!(d.path().join(p).exists(), "{p}");
    }
    assert_eq!(read(d.path(), ".tempa/commands/db/migrate.md"), read(d.path(), ".claude/commands/db/migrate.md"));
    assert!(read(d.path(), ".tempa/mcp.toml").contains("[servers.pg]"));
    let cfg = Config::load(d.path()).unwrap();
    assert!(cfg.harness.contains(&("format".to_string(), "cargo fmt --check".to_string())));
    assert!(cfg.gates.protected_paths.contains(&"secrets/**".to_string()));
}

#[test]
fn dry_run_writes_nothing() {
    let d = fixture_repo("claude-heavy");
    let dry = import(d.path(), false).unwrap();
    assert!(!d.path().join("AGENTS.md").exists());
    assert!(!d.path().join(".tempa").exists());
    assert!(!d.path().join("tempa.toml").exists());
    let e = fixture_repo("claude-heavy");
    let real = import(e.path(), true).unwrap();
    assert_eq!(dry.written, real.written);
    assert_eq!(dry.harness_added, real.harness_added);
    assert_eq!(dry.protected_added, real.protected_added);
    assert_eq!(dry.duplicates_skipped, real.duplicates_skipped);
}

#[test]
fn import_then_sync_then_import_again_is_stable() {
    let d = fixture_repo("claude-heavy");
    import(d.path(), true).unwrap();
    sync(d.path()).unwrap();
    let agents = read(d.path(), "AGENTS.md");
    let again = import(d.path(), true).unwrap();
    assert!(again.written.is_empty(), "{:?}", again.written);
    assert!(again.harness_added.is_empty() && again.protected_added.is_empty());
    assert_eq!(read(d.path(), "AGENTS.md"), agents);
    assert_eq!(drift(d.path()).unwrap(), vec![]);
}

#[test]
fn absorbs_direct_edit_of_generated_command() {
    let d = fixture_repo("claude-heavy");
    import(d.path(), true).unwrap();
    sync(d.path()).unwrap();
    let p = d.path().join(".claude/commands/review.md");
    std::fs::write(&p, std::fs::read_to_string(&p).unwrap() + "Fokus ke keamanan.\n").unwrap();
    import(d.path(), true).unwrap();
    assert!(read(d.path(), ".tempa/commands/review.md").ends_with("Fokus ke keamanan.\n"));
    assert!(!read(d.path(), ".tempa/commands/review.md").contains("generated by tempa"));
    sync(d.path()).unwrap();
    assert_eq!(drift(d.path()).unwrap(), vec![]);
}

#[test]
fn absorbs_untracked_new_command_and_claude_md_edit() {
    let d = fixture_repo("claude-heavy");
    import(d.path(), true).unwrap();
    sync(d.path()).unwrap();
    write(d.path(), ".claude/commands/baru.md", "Perintah baru\n");
    let c = d.path().join("CLAUDE.md");
    std::fs::write(&c, std::fs::read_to_string(&c).unwrap() + "\n## Area terlarang\n\nlegacy/\n").unwrap();
    import(d.path(), true).unwrap();
    assert_eq!(read(d.path(), ".tempa/commands/baru.md"), "Perintah baru\n");
    assert!(read(d.path(), "AGENTS.md").contains("## Area terlarang\n\nlegacy/"));
    sync(d.path()).unwrap();
    assert_eq!(drift(d.path()).unwrap(), vec![]);
}

#[test]
fn conflicting_handwritten_command_is_gap_not_overwrite() {
    let d = fixture_repo("claude-heavy");
    write(d.path(), ".tempa/commands/review.md", "versi tempa\n");
    let r = import(d.path(), true).unwrap();
    assert_eq!(read(d.path(), ".tempa/commands/review.md"), "versi tempa\n");
    assert!(r.gaps.iter().any(|g| g.contains(".tempa/commands/review.md")), "{:?}", r.gaps);
}

#[test]
fn invalid_settings_json_is_clear_error() {
    let d = fixture_repo("claude-heavy");
    std::fs::write(d.path().join(".claude/settings.json"), "{").unwrap();
    let e = import(d.path(), true).unwrap_err();
    assert!(e.0.contains("bukan JSON valid"), "{}", e.0);
}

#[test]
fn repo_without_any_agent_files() {
    let d = tempfile::tempdir().unwrap();
    let r = import(d.path(), true).unwrap();
    assert_eq!(r.written, vec!["tempa.toml".to_string()]);
    assert!(r.gaps.is_empty());
}
